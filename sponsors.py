def sponsorship_signal(company):
    """Return 1.0 if the company matches a known H-1B sponsor, else 0.0.
    Substring match so "Amazon Web Services" matches "amazon".
    0.0 means no sponsorship history on file, not a definite no."""
    if not company:
        return 0.0
    company_lower = company.lower().strip()
    for sponsor in KNOWN_SPONSORS:
        if sponsor in company_lower or company_lower in sponsor:
            return 1.0
    return 0.0


